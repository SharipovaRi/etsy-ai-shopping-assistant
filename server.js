// CREATE SAFE PRODUCT RESPONSE
// ============================================================

function buildRecommendation(
  product,
  aiRecommendation = null
) {
  if (!product) {
    return null;
  }

  const allowedMatchLevels = [
    "Strong",
    "Good",
    "Partial"
  ];

  let matchLevel = "Good";

  if (
    aiRecommendation &&
    allowedMatchLevels.includes(
      aiRecommendation.match_level
    )
  ) {
    matchLevel =
      aiRecommendation.match_level;
  }

  return {
    listing_id:
      product.listing_id ?? "",

    title:
      product.title ||
      "Untitled product",

    category:
      product.category ||
      "Gift",

    subcategory:
      product.subcategory ||
      "",

    description:
      product.description ||
      "",

    price:
      product.price ?? 0,

    personalizable:
      product.personalizable ??
      false,

    personalization_options:
      toArray(
        product.personalization_options
      ),

    style:
      toArray(product.style),

    materials:
      toArray(product.materials),

    colors:
      toArray(product.colors),

    recipients:
      toArray(product.recipients),

    occasions:
      toArray(product.occasions),

    interests:
      toArray(product.interests),

    estimated_delivery_days:
      product.estimated_delivery_days ??
      null,

    rating:
      product.rating ?? null,

    review_count:
      product.review_count ?? 0,

    review_themes:
      toArray(product.review_themes),

    match_level:
      matchLevel,

    reason:
      aiRecommendation?.reason ||
      "This product matches several parts of your shopping request.",

    requirements_met:
      Array.isArray(
        aiRecommendation?.requirements_met
      )
        ? aiRecommendation.requirements_met
        : [],

    requirements_not_met:
      Array.isArray(
        aiRecommendation?.requirements_not_met
      )
        ? aiRecommendation.requirements_not_met
        : [],

    review_insight:
      aiRecommendation?.review_insight ||
      ""
  };
}


