// ============================================================
// HELPER: NORMALIZE
// ============================================================

function normalize(value) {
  if (
    value === null ||
    value === undefined
  ) {
    return "";
  }

  if (Array.isArray(value)) {
    return value
      .join(" ")
      .toLowerCase()
      .trim();
  }

  return String(value)
    .toLowerCase()
    .trim();
}


// ============================================================
// HELPER: TOKENIZE
// ============================================================

function tokenize(value) {
  return normalize(value)
    .replace(/[^a-z0-9\s]/g, " ")
    .split(/\s+/)
    .filter(word => word.length > 1);
}


// ============================================================
// HELPER: UNIQUE VALUES
// ============================================================

function unique(values) {
  return [
    ...new Set(
      values.filter(Boolean)
    )
  ];
}


// ============================================================
// HELPER: CONVERT VALUE TO ARRAY
// ============================================================

function toArray(value) {
  if (Array.isArray(value)) {
    return value;
  }

  if (
    value === null ||
    value === undefined ||
    value === ""
  ) {
    return [];
  }

  return [value];
}


// ============================================================
// BUILD SEARCHABLE PRODUCT TEXT
// ============================================================

function productText(product) {
  if (!product) {
    return "";
  }

  return normalize([
    product.title,
    product.category,
    product.subcategory,
    product.description,

    ...toArray(product.style),
    ...toArray(product.materials),
    ...toArray(product.colors),
    ...toArray(product.recipients),
    ...toArray(product.occasions),
    ...toArray(product.interests),
    ...toArray(product.personalization_options),
    ...toArray(product.review_themes)
  ]);
}


// ============================================================
// SEARCH PRODUCTS
// ============================================================

function searchProducts(
  criteria = {},
  searchTerms = []
) {
  const terms = unique(
    tokenize([
      ...toArray(searchTerms),
      criteria.recipient,
      criteria.occasion,
      criteria.category,
      ...toArray(criteria.style),
      ...toArray(criteria.interests)
    ])
  );

  const scoredProducts = products
    .filter(
      product =>
        product &&
        typeof product === "object"
    )
    .map(product => {
      let score = 0;

      const searchableText =
        productText(product);

      // ------------------------------------------------------
      // KEYWORD MATCHING
      // ------------------------------------------------------

      for (const term of terms) {
        if (
          searchableText.includes(term)
        ) {
          score += 2;
        }
      }


      // ------------------------------------------------------
      // CATEGORY
      // ------------------------------------------------------

      if (criteria.category) {
        const requestedCategory =
          normalize(criteria.category);

        const productCategory =
          normalize([
            product.category,
            product.subcategory
          ]);

        if (
          productCategory.includes(
            requestedCategory
          ) ||
          requestedCategory.includes(
            normalize(product.category)
          )
        ) {
          score += 10;
        }
      }


      // ------------------------------------------------------
      // BUDGET
      // ------------------------------------------------------

      const maxBudget =
        Number(criteria.max_budget);

      const productPrice =
        Number(product.price);

      if (
        Number.isFinite(maxBudget) &&
        maxBudget > 0 &&
        Number.isFinite(productPrice)
      ) {
        if (
          productPrice <= maxBudget
        ) {
          score += 8;
        } else {
          score -= 8;
        }
      }


      // ------------------------------------------------------
      // PERSONALIZATION
      // ------------------------------------------------------

      if (
        criteria.personalization_required === true
      ) {
        if (
          product.personalizable === true
        ) {
          score += 9;
        } else {
          score -= 10;
        }
      }


      // ------------------------------------------------------
      // DELIVERY
      // ------------------------------------------------------

      const maxDelivery =
        Number(
          criteria.max_delivery_days
        );

      const productDelivery =
        Number(
          product.estimated_delivery_days
        );

      if (
        Number.isFinite(maxDelivery) &&
        maxDelivery > 0 &&
        Number.isFinite(productDelivery)
      ) {
        if (
          productDelivery <= maxDelivery
        ) {
          score += 8;
        } else {
          score -= 7;
        }
      }


      // ------------------------------------------------------
      // RECIPIENT
      // ------------------------------------------------------

      if (criteria.recipient) {
        const requestedRecipient =
          normalize(criteria.recipient);

        const productRecipients =
          normalize(product.recipients);

        if (
          productRecipients.includes(
            requestedRecipient
          )
        ) {
          score += 5;
        }
      }


      // ------------------------------------------------------
      // OCCASION
      // ------------------------------------------------------

      if (criteria.occasion) {
        const requestedOccasion =
          normalize(criteria.occasion);

        const productOccasions =
          normalize(product.occasions);

        if (
          productOccasions.includes(
            requestedOccasion
          )
        ) {
          score += 5;
        }
      }


      // ------------------------------------------------------
      // STYLE
      // ------------------------------------------------------

      for (
        const style
        of toArray(criteria.style)
      ) {
        if (
          normalize(product.style)
            .includes(
              normalize(style)
            )
        ) {
          score += 4;
        }
      }


      // ------------------------------------------------------
      // INTERESTS
      // ------------------------------------------------------

      for (
        const interest
        of toArray(criteria.interests)
      ) {
        if (
          searchableText.includes(
            normalize(interest)
          )
        ) {
          score += 4;
        }
      }


      // ------------------------------------------------------
      // RATINGS
      // ------------------------------------------------------

      const rating =
        Number(product.rating);

      if (Number.isFinite(rating)) {
        if (rating >= 4.8) {
          score += 3;
        } else if (rating >= 4.5) {
          score += 2;
        }
      }


      return {
        product,
        score
      };
    });


  scoredProducts.sort(
    (a, b) => {
      if (b.score !== a.score) {
        return b.score - a.score;
      }

      return (
        Number(
          b.product?.rating || 0
        ) -
        Number(
          a.product?.rating || 0
        )
      );
    }
  );


  return scoredProducts
    .slice(0, 20)
    .map(item => item.product)
    .filter(Boolean);
}


// ============================================================
// PARSE GEMINI JSON
// ============================================================

function parseJSONResponse(text) {
  if (!text) {
    throw new Error(
      "Gemini returned an empty response."
    );
  }

  const cleaned = text
    .replace(/```json/gi, "")
    .replace(/```/g, "")
    .trim();

  try {
    return JSON.parse(cleaned);
  } catch (error) {
    console.error(
      "Could not parse Gemini response:"
    );

    console.error(cleaned);

    throw new Error(
      "Gemini returned invalid structured data."
    );
  }
}


// ============================================================
// CALL GEMINI
// ============================================================

async function callGemini(
  systemInstruction,
  input
) {
  const maxAttempts = 3;

  for (
    let attempt = 1;
    attempt <= maxAttempts;
    attempt++
  ) {
    try {
      const response =
        await ai.models.generateContent({
          model: GEMINI_MODEL,

          contents: input,

          config: {
            systemInstruction,

            responseMimeType:
              "application/json",

            temperature: 0.2
          }
        });

      if (!response.text) {
        throw new Error(
          "Gemini returned no response."
        );
      }

      return response.text
        .replace(/```json/gi, "")
        .replace(/```/g, "")
        .trim();

    } catch (error) {
      const status =
        Number(
          error.status ||
          error.code
        );

      const temporaryError =
        status === 429 ||
        status === 503;

      if (
        temporaryError &&
        attempt < maxAttempts
      ) {
        console.log(
          `Gemini temporarily unavailable. Retrying ${attempt}/${maxAttempts}...`
        );

        await new Promise(
          resolve =>
            setTimeout(
              resolve,
              attempt * 2000
            )
        );

        continue;
      }

      throw error;
    }
  }

  throw new Error(
    "Gemini request failed."
  );
}


