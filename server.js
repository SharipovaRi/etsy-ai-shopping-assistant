// RECOMMENDATION ENDPOINT
// ============================================================

app.post(
  "/api/recommend",
  async (req, res) => {
    try {

      // ------------------------------------------------------
      // VALIDATE SHOPPER REQUEST
      // ------------------------------------------------------

      const shopperRequest =
        typeof req.body?.request ===
        "string"
          ? req.body.request.trim()
          : "";


      if (!shopperRequest) {
        return res
          .status(400)
          .json({
            error:
              "Please describe what you're looking for."
          });
      }


      if (
        shopperRequest.length < 12
      ) {
        return res
          .status(400)
          .json({
            error:
              "Please add a little more detail about the gift you're looking for."
          });
      }


      // ------------------------------------------------------
      // STEP 1:
      // EXTRACT SHOPPING CRITERIA
      // ------------------------------------------------------

      const extractionText =
        await callGemini(
          EXTRACTION_PROMPT,
          `
SHOPPER REQUEST:

${shopperRequest}
          `.trim()
        );


      const extraction =
        parseJSONResponse(
          extractionText
        );


      const criteria =
        extraction?.criteria &&
        typeof extraction.criteria ===
          "object"
          ? extraction.criteria
          : {};


      // ------------------------------------------------------
      // CLARIFICATION
      // ------------------------------------------------------

      if (
        extraction?.needs_clarification ===
        true
      ) {
        return res.json({
          needs_clarification:
            true,

          clarifying_question:
            extraction.clarifying_question ||
            "Could you tell me a little more about what you're looking for?"
        });
      }


      // ------------------------------------------------------
      // STEP 2:
      // SEARCH PRODUCT DATASET
      // ------------------------------------------------------

      const candidates =
        searchProducts(
          criteria,
          extraction?.search_terms || []
        );


      console.log(
        `Found ${candidates.length} candidate products.`
      );


      if (
        candidates.length === 0
      ) {
        return res
          .status(404)
          .json({
            error:
              "No suitable products were found for this request."
          });
      }


      // ------------------------------------------------------
      // STEP 3:
      // ASK GEMINI TO COMPARE CANDIDATES
      // ------------------------------------------------------

      const comparisonInput = `
SHOPPER'S ORIGINAL REQUEST:

${shopperRequest}


STRUCTURED SHOPPING CRITERIA:

${JSON.stringify(
  criteria,
  null,
  2
)}


CANDIDATE PRODUCTS:

${JSON.stringify(
  candidates,
  null,
  2
)}
      `.trim();


      const comparisonText =
        await callGemini(
          COMPARISON_PROMPT,
          comparisonInput
        );


      const comparison =
        parseJSONResponse(
          comparisonText
        );


      const aiRecommendations =
        Array.isArray(
          comparison?.recommendations
        )
          ? comparison.recommendations
          : [];


      // ------------------------------------------------------
      // CREATE CANDIDATE MAP
      // ------------------------------------------------------

      const candidateMap =
        new Map();


      for (
        const product
        of candidates
      ) {
        if (
          !product ||
          product.listing_id ===
            undefined ||
          product.listing_id ===
            null
        ) {
          continue;
        }

        candidateMap.set(
          String(product.listing_id),
          product
        );
      }


      // ------------------------------------------------------
      // STEP 4:
      // VERIFY GEMINI RECOMMENDATIONS
      // ------------------------------------------------------

      const recommendations = [];

      const usedIds =
        new Set();


      for (
        const aiRecommendation
        of aiRecommendations
      ) {
        if (!aiRecommendation) {
          continue;
        }


        const listingId =
          String(
            aiRecommendation
              .listing_id ?? ""
          );


        if (!listingId) {
          continue;
        }


        const product =
          candidateMap.get(
            listingId
          );


        // Ignore hallucinated/invalid IDs.
        if (!product) {
          console.warn(
            `Gemini returned unknown listing ID: ${listingId}`
          );

          continue;
        }


        if (
          usedIds.has(listingId)
        ) {
          continue;
        }


        const recommendation =
          buildRecommendation(
            product,
            aiRecommendation
          );


        if (!recommendation) {
          continue;
        }


        usedIds.add(listingId);

        recommendations.push(
          recommendation
        );


        if (
          recommendations.length === 3
        ) {
          break;
        }
      }


      // ------------------------------------------------------
      // FALLBACK
      //
      // If Gemini returned fewer than three valid IDs,
      // fill remaining positions with real dataset products.
      // ------------------------------------------------------

      if (
        recommendations.length < 3
      ) {
        for (
          const product
          of candidates
        ) {
          if (!product) {
            continue;
          }


          const listingId =
            String(
              product.listing_id ?? ""
            );


          if (!listingId) {
            continue;
          }


          if (
            usedIds.has(listingId)
          ) {
            continue;
          }


          const recommendation =
            buildRecommendation(
              product,
              null
            );


          if (!recommendation) {
            continue;
          }


          usedIds.add(listingId);

          recommendations.push(
            recommendation
          );


          if (
            recommendations.length === 3
          ) {
            break;
          }
        }
      }


      // ------------------------------------------------------
      // FINAL SAFETY CHECK
      // ------------------------------------------------------

      const safeRecommendations =
        recommendations
          .filter(
            recommendation =>
              recommendation &&
              typeof recommendation ===
                "object"
          )
          .slice(0, 3);


      if (
        safeRecommendations.length ===
        0
      ) {
        throw new Error(
          "No valid recommendations could be created."
        );
      }


      console.log(
        `Returning ${safeRecommendations.length} recommendations.`
      );


      // ------------------------------------------------------
      // RESPONSE
      // ------------------------------------------------------

      return res.json({
        needs_clarification:
          false,

        original_request:
          shopperRequest,

        criteria,

        recommendations:
          safeRecommendations
      });

    } catch (error) {

      // ------------------------------------------------------
      // ERROR HANDLING
      // ------------------------------------------------------

      console.error(
        "Recommendation error:"
      );

      console.error(error);


      const status =
        Number(
          error?.status ||
          error?.code
        );


      if (status === 429) {
        return res
          .status(503)
          .json({
            error:
              "The AI service is receiving too many requests right now. Please wait a moment and try again."
          });
      }


      if (status === 503) {
        return res
          .status(503)
          .json({
            error:
              "The AI service is temporarily unavailable. Please try again in a moment."
          });
      }


      return res
        .status(500)
        .json({
          error:
            "We couldn't complete your recommendation right now. Please try again."
        });
    }
  }
);


